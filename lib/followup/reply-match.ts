/**
 * Deciding whether something that arrived is really a customer reply.
 *
 * This is the judgement that stops the reminders, so a false positive is
 * expensive in a specific way: Selryn goes quiet about a deal nobody actually
 * answered, and the seller never learns it was dropped. Three things get
 * mistaken for replies, and each is excluded here:
 *
 *  1. **Our own mail.** Threads loop back through shared mailboxes and CRM
 *     logging. Direction comes from the record, never from guessing.
 *  2. **Bounces.** A delivery failure is mail arriving *about* the message,
 *     not an answer to it, and it means the opposite: nobody read it.
 *  3. **Auto-replies.** Out-of-office and ticket acknowledgements are
 *     machines. Treating one as engagement is how a deal goes quiet for three
 *     weeks while the product reports it as answered.
 *
 * Pure, so each exclusion is testable without a mailbox.
 */

export interface InboundCandidate {
  /** From the provider's own direction field, not inferred from the address. */
  actorType: string;
  eventType: string;
  occurredAt: Date;
  subject: string | null;
  /** Provider headers when available — absent for CRM-sourced records. */
  headers?: Record<string, string | undefined>;
  /** The opportunity the provider associated the record with. */
  opportunityId: string | null;
}

export type ReplyRejection =
  | "not_inbound"
  | "bounce"
  | "auto_reply"
  | "unlinked"
  | "before_send";

export type ReplyVerdict =
  | { isReply: true }
  | { isReply: false; reason: ReplyRejection };

/** Subjects that mark mail generated by a machine rather than a person. */
const AUTO_SUBJECT = /^\s*(?:re:\s*)*(?:automatic reply|out of office|auto(?:matic)?[- ]reply|autoreply|away from (?:the )?office|undeliverable|delivery status notification|mail delivery (?:failed|subsystem)|returned mail)\b/i;

const BOUNCE_SUBJECT = /\b(?:undeliverable|delivery status notification|mail delivery (?:failed|subsystem)|returned mail|failure notice)\b/i;

/**
 * Headers that mean "a machine sent this".
 *
 * RFC 3834 defines `auto-submitted`; the `x-auto*` family predates it and is
 * still what most vacation responders set, so both are checked.
 */
function looksAutomated(headers: Record<string, string | undefined>): boolean {
  const lower: Record<string, string> = {};
  for (const [k, v] of Object.entries(headers)) {
    if (v != null) lower[k.toLowerCase()] = String(v).toLowerCase();
  }

  const autoSubmitted = lower["auto-submitted"];
  if (autoSubmitted && autoSubmitted !== "no") return true;

  // Any positive value counts: responders disagree on 1 vs yes vs auto-replied.
  for (const key of ["x-autoreply", "x-autorespond", "x-auto-response-suppress"]) {
    if (lower[key]) return true;
  }
  if (lower["precedence"] && ["auto_reply", "bulk", "junk"].includes(lower["precedence"])) {
    return true;
  }
  // A list posting is not a reply to our deal.
  if (lower["list-id"] || lower["list-unsubscribe"]) return true;

  return false;
}

export function classifyInbound(
  candidate: InboundCandidate,
  opts: { sentAt: Date | null; opportunityId: string }
): ReplyVerdict {
  // 1. Ours, or a system record — never a reply.
  if (candidate.actorType !== "buyer") return { isReply: false, reason: "not_inbound" };
  if (!candidate.eventType.startsWith("email.")) {
    return { isReply: false, reason: "not_inbound" };
  }

  // 2. It has to be about this deal. A reply on another thread must not
  //    silence this one.
  if (candidate.opportunityId !== opts.opportunityId) {
    return { isReply: false, reason: "unlinked" };
  }

  // 3. Mail that predates the follow-up answers something else.
  if (opts.sentAt && candidate.occurredAt < opts.sentAt) {
    return { isReply: false, reason: "before_send" };
  }

  const subject = candidate.subject ?? "";
  if (BOUNCE_SUBJECT.test(subject)) return { isReply: false, reason: "bounce" };
  if (AUTO_SUBJECT.test(subject)) return { isReply: false, reason: "auto_reply" };
  if (candidate.headers && looksAutomated(candidate.headers)) {
    return { isReply: false, reason: "auto_reply" };
  }

  return { isReply: true };
}

/** The first genuine reply to a sent follow-up, or null. */
export function firstReply(
  candidates: InboundCandidate[],
  opts: { sentAt: Date | null; opportunityId: string }
): InboundCandidate | null {
  return (
    [...candidates]
      .sort((a, b) => a.occurredAt.getTime() - b.occurredAt.getTime())
      .find((c) => classifyInbound(c, opts).isReply) ?? null
  );
}
